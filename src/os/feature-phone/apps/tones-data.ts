/** 铃声设置（设备裸键 tones:conf；tones app 经 AppStore 的 conf 键读写同一位置） */
export interface TonesConf {
  /** RINGTONES 索引（等于 RINGTONES.length 时为用户自编曲调） */
  ringIdx: number
  /** MSG_ALERTS 索引 */
  msgIdx: number
  /** 铃声音量 1..4（0 留给情景模式 Silent，由 profiles 写入） */
  ringLevel: number
  /** 来电提醒方式：连续 / 渐强 / 哔一声 */
  alert: 'ring' | 'ascending' | 'once'
  keyBeep: boolean
  warnTone: boolean
  vibrate: boolean
  /** 短信提示音开关（Silent 情景关） */
  msgSound: boolean
}

